-- ResearchTrace Database Initialization Script for Docker Container
-- Automatically executed on first container database creation

CREATE SCHEMA IF NOT EXISTS public;

CREATE TABLE IF NOT EXISTS public.project (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description character varying(255),
    name character varying(255),
    status character varying(255)
);

CREATE TABLE IF NOT EXISTS public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email character varying(255),
    name character varying(255),
    role character varying(255)
);

CREATE TABLE IF NOT EXISTS public.project_member (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint,
    user_id bigint,
    role character varying(255)
);

CREATE TABLE IF NOT EXISTS public.milestone (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint,
    title character varying(255),
    description character varying(255),
    status character varying(255),
    due_date date,
    weight numeric(6,2)
);

CREATE TABLE IF NOT EXISTS public.meeting (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint,
    title character varying(255),
    meeting_date date NOT NULL,
    notes text
);

CREATE TABLE IF NOT EXISTS public.task (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint,
    meeting_id bigint,
    milestone_id bigint,
    assignee_id bigint,
    task_suggestion_id bigint,
    research_decision_id bigint,
    experiment_id bigint,
    title character varying(255),
    description text,
    status character varying(255),
    due_date date,
    created_at timestamp without time zone,
    updated_at timestamp without time zone
);

CREATE TABLE IF NOT EXISTS public.task_suggestion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint,
    meeting_id bigint,
    milestone_id bigint,
    assignee_id bigint,
    accepted_task_id bigint,
    research_decision_id bigint,
    experiment_id bigint,
    title character varying(255),
    description text,
    source_excerpt text,
    status character varying(255),
    assignee_name character varying(255),
    confidence numeric(3,2),
    due_date date
);

CREATE TABLE IF NOT EXISTS public.task_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL,
    old_status character varying(255),
    new_status character varying(255) NOT NULL,
    changed_by_user_id bigint,
    changed_at timestamp without time zone NOT NULL
);

CREATE TABLE IF NOT EXISTS public.extraction_review (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id bigint NOT NULL,
    status character varying(255) NOT NULL,
    extraction_json text
);

CREATE TABLE IF NOT EXISTS public.research_decision (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL,
    meeting_id bigint,
    extraction_review_id bigint,
    supersedes_decision_id bigint,
    created_by_user_id bigint,
    title character varying(255) NOT NULL,
    decision_text text,
    rationale text,
    source_reference text,
    status character varying(255) NOT NULL,
    decided_at date,
    created_at timestamp(6) without time zone NOT NULL
);

CREATE TABLE IF NOT EXISTS public.experiment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL,
    meeting_id bigint,
    research_decision_id bigint,
    created_by_user_id bigint,
    title character varying(255) NOT NULL,
    hypothesis text,
    method text,
    source_reference text,
    status character varying(255) NOT NULL,
    started_at date,
    completed_at date,
    created_at timestamp(6) without time zone NOT NULL
);

CREATE TABLE IF NOT EXISTS public.result (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL,
    meeting_id bigint,
    experiment_id bigint NOT NULL,
    created_by_user_id bigint,
    summary text NOT NULL,
    data_or_metric text,
    comparison text,
    source_reference text,
    observed_at date,
    created_at timestamp(6) without time zone NOT NULL
);

CREATE TABLE IF NOT EXISTS public.research_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL,
    meeting_id bigint,
    research_decision_id bigint,
    experiment_id bigint,
    result_id bigint,
    research_change_id bigint,
    task_id bigint,
    created_by_user_id bigint,
    title character varying(255) NOT NULL,
    description text,
    event_type character varying(255) NOT NULL,
    source_reference text,
    occurred_at timestamp(6) without time zone NOT NULL,
    created_at timestamp(6) without time zone NOT NULL
);

CREATE TABLE IF NOT EXISTS public.research_change (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL,
    meeting_id bigint,
    title character varying(255) NOT NULL,
    previous_approach text,
    new_approach text,
    reason text,
    change_type character varying(255) NOT NULL,
    status character varying(255) NOT NULL,
    source_reference text,
    detected_at timestamp(6) without time zone NOT NULL,
    created_at timestamp(6) without time zone NOT NULL
);

